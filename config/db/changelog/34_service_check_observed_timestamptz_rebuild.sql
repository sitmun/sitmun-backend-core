-- Oracle raises ORA-01439 when ALTER MODIFY changes TIMESTAMP to
-- TIMESTAMP WITH TIME ZONE and the column already has values.
-- Copy each value onto a new column as UTC. The backend stores these
-- instants with hibernate.jdbc.time_zone set to UTC.
-- The later ALTER changeset sees TIMESTAMP(6) WITH TIME ZONE and is skipped.

--changeset sitmun:34-service-check-sec-observed-rebuild-oracle dbms:oracle splitStatements:false endDelimiter:/
DECLARE
  l_type VARCHAR2(128);
  l_tz NUMBER;
  l_nullable VARCHAR2(1);
BEGIN
  BEGIN
    SELECT data_type, nullable INTO l_type, l_nullable
    FROM user_tab_columns
    WHERE table_name = 'STM_SERVICE_CHECK' AND column_name = 'SEC_OBSERVED';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      l_type := NULL;
      l_nullable := NULL;
  END;

  SELECT COUNT(*) INTO l_tz
  FROM user_tab_columns
  WHERE table_name = 'STM_SERVICE_CHECK' AND column_name = 'SEC_OBSERVED_TZ';

  IF l_type LIKE '%WITH TIME ZONE' THEN
    IF l_nullable = 'Y' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK MODIFY (SEC_OBSERVED NOT NULL)';
    END IF;
    IF l_tz = 1 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK DROP COLUMN SEC_OBSERVED_TZ';
    END IF;
  ELSE
    IF l_tz = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK ADD (SEC_OBSERVED_TZ TIMESTAMP(6) WITH TIME ZONE)';
    END IF;
    IF l_type IS NOT NULL THEN
      EXECUTE IMMEDIATE 'UPDATE STM_SERVICE_CHECK SET SEC_OBSERVED_TZ = FROM_TZ(SEC_OBSERVED, ''UTC'') WHERE SEC_OBSERVED_TZ IS NULL';
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK MODIFY (SEC_OBSERVED_TZ NOT NULL)';
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK DROP COLUMN SEC_OBSERVED';
    ELSE
      EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK MODIFY (SEC_OBSERVED_TZ NOT NULL)';
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE STM_SERVICE_CHECK RENAME COLUMN SEC_OBSERVED_TZ TO SEC_OBSERVED';
  END IF;
END;
