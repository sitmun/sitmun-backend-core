MERGE INTO STM_SEQUENCE t
USING (SELECT 'LTR_ID' n, 0 v FROM DUAL) s
ON (t.SEQ_NAME = s.n)
WHEN NOT MATCHED THEN INSERT (SEQ_NAME, SEQ_COUNT) VALUES (s.n, s.v);

MERGE INTO STM_SEQUENCE t
USING (SELECT 'LTV_ID' n, 0 v FROM DUAL) s
ON (t.SEQ_NAME = s.n)
WHEN NOT MATCHED THEN INSERT (SEQ_NAME, SEQ_COUNT) VALUES (s.n, s.v);

